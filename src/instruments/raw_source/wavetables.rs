#[derive(Clone, Copy)]
pub enum Waveform {
    None,
    Sine,
    Saw,
}

pub struct WavetableLookup {
    waveform: Waveform,
    phase: f32,
}

impl WavetableLookup {
    pub fn new(waveform: Waveform) -> Self {
        Self {
            waveform: waveform,
            phase: 0.0,
        }
    }

    pub fn next_value(&mut self, delta: f32) -> f32 {
        self.phase += delta;

        while self.phase >= 1.0 {
            self.phase = self.phase - 1.0;
        }

        WavetableLookup::get_value(self.waveform, self.phase)
    }

    fn get_value(waveform: Waveform, phase: f32) -> f32 {
        if phase < 0.0 || phase >= 1.0 {
            return 0.0;
        }

        let table: &[f32] = match waveform {
            Waveform::Sine => &SINE_TABLE,
            Waveform::Saw => &SAW_TABLE,
            Waveform::None => &EMPTY_TABLE,
        };

        let table_size = table.len();
        let position = table_size as f32 * phase;
        let index = position as usize;
        let frac = position.fract();

        // Interpolate if we're between two data points
        // TODO: Use different Interpolation methods
        let a = table[index];
        let b = table[(index + 1) % table_size];

        a + (b - a) * frac
    }
}

